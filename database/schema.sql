-- =========================================================
-- Pet Feeder — skema database (Supabase / PostgreSQL)
-- Jalankan di Supabase: SQL Editor → New query → tempel → Run.
-- Aman dijalankan ulang: tabel lama dihapus dulu (DATA IKUT HILANG).
--
-- Perubahan dari skema laporan:
--   • feeding_schedule tanpa portion_g (dropper dibuka berdasarkan waktu)
--   • feedings.dispensed_g = berat terukur load cell setelah dispense (acak)
--   • pets.device_id UNIQUE (1 feeder = 1 pet), pets.photo_url
--   • devices.hopper_level_pct + hopper_read_at (sensor ultrasonik)
--   • fungsi reclassify_feedings() untuk menghitung status severity
--   • feedings unik per (device_id, scheduled_at)
--   • login Supabase Auth: users.id = auth.users.id (trigger), devices.user_id null = belum
--     dihubungkan ke akun, RLS hanya mengizinkan membaca data milik sendiri
-- =========================================================

drop table if exists public.feedings cascade;
drop table if exists public.feeding_schedule cascade;
drop table if exists public.pets cascade;
drop table if exists public.devices cascade;
drop table if exists public.users cascade;

-- ---------------------------------------------------------- tables
create table public.users (
  id    uuid primary key default gen_random_uuid(),
  email text not null unique
);

create table public.devices (
  id                 bigint generated by default as identity primary key,
  user_id            uuid references public.users (id) on delete set null, -- null = belum dihubungkan ke akun
  name               text not null,
  api_key_hash       text not null unique,            -- SHA-256 hex dari API key alat
  paired_at          timestamptz not null default now(),
  last_seen_at       timestamptz,
  bowl_weight_g      numeric(6,1) check (bowl_weight_g >= 0),
  bowl_read_at       timestamptz,
  hopper_capacity_g  integer not null check (hopper_capacity_g > 0),
  hopper_refilled_at timestamptz,
  hopper_level_pct   numeric(5,1) check (hopper_level_pct between 0 and 100),
  hopper_read_at     timestamptz
);

create table public.pets (
  id               bigint generated by default as identity primary key,
  device_id        bigint not null unique references public.devices (id) on delete cascade,
  name             text not null,
  watch_pct        smallint not null default 15,
  moderate_pct     smallint not null default 30,
  urgent_pct       smallint not null default 50,
  moderate_session smallint not null default 2 check (moderate_session between 1 and 10),
  photo_url        text,
  constraint pets_threshold_order check (
    watch_pct > 0 and watch_pct < moderate_pct and moderate_pct < urgent_pct and urgent_pct <= 100
  )
);

create table public.feeding_schedule (
  id        bigint generated by default as identity primary key,
  device_id bigint not null references public.devices (id) on delete cascade,
  feed_time time not null,                             -- jam lokal (WIB)
  is_active boolean not null default true,
  unique (device_id, feed_time)
);

create table public.feedings (
  id           bigint generated by default as identity primary key,
  device_id    bigint not null references public.devices (id) on delete cascade,
  pet_id       bigint not null references public.pets (id) on delete cascade,
  schedule_id  bigint references public.feeding_schedule (id) on delete set null,
  scheduled_at timestamptz not null,
  dispensed_g  numeric(6,1) not null check (dispensed_g >= 0),
  leftover_g   numeric(6,1) check (leftover_g >= 0 and leftover_g <= dispensed_g), -- null = masih dipantau
  status       text not null default 'normal' check (status in ('normal', 'watch', 'moderate', 'urgent')),
  synced_at    timestamptz not null default now(),
  constraint feedings_device_scheduled_unique unique (device_id, scheduled_at) -- alat kirim ulang → 409, bukan duplikat
);

create index feedings_pet_time_idx on public.feedings (pet_id, scheduled_at desc);

-- ---------------------------------------------------------- severity
-- Sama dengan js/severity.js:
--   consumed = (dispensed - leftover) / dispensed * 100
--   baseline = rata-rata consumed dari p_window sesi NORMAL terakhir (minimal 3)
--   drop     = (baseline - consumed) / baseline * 100
--   urgent  : drop >= urgent_pct
--   moderate: drop >= moderate_pct selama >= moderate_session sesi beruntun
--   watch   : drop >= watch_pct
-- Sesi dengan leftover_g null (masih dipantau) dilewati.
create or replace function public.reclassify_feedings(p_pet_id bigint, p_window int default 10)
returns void
language plpgsql
as $$
declare
  v_pet      public.pets%rowtype;
  v_f        record;
  v_normals  numeric[] := '{}';
  v_n        int;
  v_streak   int := 0;
  v_consumed numeric;
  v_baseline numeric;
  v_drop     numeric;
  v_status   text;
begin
  select * into v_pet from public.pets where id = p_pet_id;
  if not found then
    raise exception 'pet % tidak ditemukan', p_pet_id;
  end if;

  for v_f in
    select id, dispensed_g, leftover_g, status
    from public.feedings
    where pet_id = p_pet_id
    order by scheduled_at, id
  loop
    continue when v_f.leftover_g is null or v_f.dispensed_g = 0;

    v_consumed := greatest(0, (v_f.dispensed_g - v_f.leftover_g) / v_f.dispensed_g) * 100;
    v_status := 'normal';
    v_n := coalesce(array_length(v_normals, 1), 0);

    if v_n >= 3 then
      select avg(x) into v_baseline from unnest(v_normals[greatest(1, v_n - p_window + 1):]) as x;
      if v_baseline > 0 then
        v_drop := greatest(0, (v_baseline - v_consumed) / v_baseline * 100);
        v_streak := case when v_drop >= v_pet.moderate_pct then v_streak + 1 else 0 end;

        if v_drop >= v_pet.urgent_pct then v_status := 'urgent';
        elsif v_streak >= v_pet.moderate_session then v_status := 'moderate';
        elsif v_drop >= v_pet.watch_pct then v_status := 'watch';
        end if;
      end if;
    end if;

    if v_status = 'normal' then
      v_normals := v_normals || v_consumed;
    end if;

    if v_f.status is distinct from v_status then
      update public.feedings set status = v_status where id = v_f.id;
    end if;
  end loop;
end;
$$;

-- hanya backend (service role) yang boleh memanggil
revoke execute on function public.reclassify_feedings(bigint, int) from public, anon, authenticated;

-- ---------------------------------------------------------- RLS
-- Browser (anon key + sesi login) hanya boleh MEMBACA data perangkat miliknya; ini juga
-- membatasi event Realtime. Semua penulisan lewat Route Handlers memakai service role key
-- (melewati RLS), dan Route Handler sendiri memfilter berdasarkan user yang login.
alter table public.users            enable row level security;
alter table public.devices          enable row level security;
alter table public.pets             enable row level security;
alter table public.feeding_schedule enable row level security;
alter table public.feedings         enable row level security;

create policy "milik sendiri" on public.users   for select to authenticated using (id = auth.uid());
create policy "milik sendiri" on public.devices for select to authenticated using (user_id = auth.uid());
create policy "milik sendiri" on public.pets    for select to authenticated
  using (device_id in (select id from public.devices where user_id = auth.uid()));
create policy "milik sendiri" on public.feeding_schedule for select to authenticated
  using (device_id in (select id from public.devices where user_id = auth.uid()));
create policy "milik sendiri" on public.feedings for select to authenticated
  using (device_id in (select id from public.devices where user_id = auth.uid()));

-- ---------------------------------------------------------- Auth
-- Setiap akun baru di Supabase Auth otomatis punya baris public.users dengan id yang sama.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  insert into public.users (id, email) values (new.id, new.email) on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- akun yang sudah ada sebelum skema ini dijalankan (tabel users di atas baru dibuat ulang)
insert into public.users (id, email)
select id, email from auth.users where email is not null
on conflict (id) do nothing;

-- ---------------------------------------------------------- Realtime
-- Dashboard update otomatis saat ada sesi makan baru / data alat berubah.
alter publication supabase_realtime add table public.feedings, public.devices;

